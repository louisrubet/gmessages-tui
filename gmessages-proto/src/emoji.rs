#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lengths() {
        assert_eq!(emoji_list(0).len(), 305);
        assert_eq!(emoji_list(1).len(), 308);
    }

    #[test]
    fn known_indices() {
        assert_eq!(EMOJI_V0[0], "😁");
        assert_eq!(EMOJI_V0[26], "😮\u{200d}💨");
        assert_eq!(EMOJI_V0[133], "🍞");
        assert_eq!(EMOJI_V0[288], "🍞");
        assert_eq!(EMOJI_V0[304], "🚸");
        assert_eq!(EMOJI_V1[0], "😅");
        assert_eq!(EMOJI_V1[19], "😮\u{200d}💨");
        assert_eq!(EMOJI_V1[294], "🍋\u{200d}🟩");
        assert_eq!(EMOJI_V1[295], "🐦\u{200d}🔥");
        assert_eq!(EMOJI_V1[307], "📐");
        assert_eq!(emoji_at(305, 0), "😁");
        assert_eq!(emoji_at(u32::MAX, 1), EMOJI_V1[(u32::MAX as usize) % 308]);
    }

    #[test]
    fn v1_derives_from_v0() {
        let mut v: Vec<&str> = Vec::new();
        for e in EMOJI_V0 {
            if !v.contains(&e) {
                v.push(e);
            }
        }
        v.extend([
            "🍋\u{200d}🟩",
            "🐦\u{200d}🔥",
            "🐲",
            "🪅",
            "🦜",
            "🏺",
            "🗿",
            "🫐",
            "⛽",
            "🍱",
            "🥡",
            "🧋",
            "🍼",
            "📐",
        ]);
        let remove = ["💻", "🤗", "💬", "👋", "😁", "😎", "😇", "🥰", "🤓", "🤩"];
        v.retain(|e| !remove.contains(e));
        assert_eq!(v, EMOJI_V1.to_vec());
    }

    #[test]
    fn noto_url() {
        assert_eq!(
            noto_svg_url("😮\u{200d}💨"),
            "https://fonts.gstatic.com/s/e/notoemoji/latest/1f62e_200d_1f4a8/emoji.svg"
        );
    }
}
