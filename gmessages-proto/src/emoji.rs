//! Pairing emoji lists (spec appendix 9).
//!
//! Google account pairing shows one emoji, `list[n mod len(list)]`, the list depending on
//! the emoji version confirmed by the phone.

/// The emoji list for an emoji version (0: 305 entries, 1: 308 entries).
///
/// Unknown versions use the version 1 list (see `NOTES.md`).
pub fn emoji_list(version: i32) -> &'static [&'static str] {
    match version {
        0 => &EMOJI_V0,
        _ => &EMOJI_V1,
    }
}

/// The emoji to show for index value `n` (unsigned) and an emoji version.
pub fn emoji_at(n: u32, version: i32) -> &'static str {
    let list = emoji_list(version);
    list[n as usize % list.len()]
}

/// URL of an SVG image of the emoji from Google's Noto font, for terminals that cannot
/// render it.
pub fn noto_svg_url(emoji: &str) -> String {
    let cps: Vec<String> = emoji
        .chars()
        .filter(|&c| c != '\u{fe0f}')
        .map(|c| format!("{:x}", c as u32))
        .collect();
    format!(
        "https://fonts.gstatic.com/s/e/notoemoji/latest/{}/emoji.svg",
        cps.join("_")
    )
}

